"""
Recovery-probability model.

Predicts P(the payment is eventually recovered within the window | state of the
case now), where "state" is the failure reason, method, amount, attempts so
far, time since failure, time of day, salary window and customer history.

Model: monotonic-constrained gradient-boosted trees (scikit-learn
HistGradientBoosting) + post-hoc probability calibration (Platt or isotonic,
chosen on a validation split). Calibration matters because the engine
multiplies this number by the amount to get an *expected recovery value*.

Evaluation uses a time-ordered train / validation / calibration / test split
at the case level (no case appears in two splits), and compares against the
previous rule-based score and a logistic-regression baseline.
"""
from __future__ import annotations

import hashlib
import json
import platform
from dataclasses import dataclass
from datetime import datetime, timezone

import joblib
import numpy as np
import sklearn
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.isotonic import IsotonicRegression
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, brier_score_loss, log_loss, roc_auc_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from app.ml import features as F
from app.ml.episodes import RulesPolicy, run_episode
from app.ml.world import BASE_WORLD, generate_cases
from app.recovery import rules

DATA_PROVENANCE = (
    "Synthetic: generated by app/ml/world.py (a documented, stylised model of payment-failure recovery) and "
    "labelled by replaying each case through the rule-based policy. Metrics describe how well the model learns "
    "that world, not production performance. Retrain on real outcomes with `python -m app.ml.train --from-db`."
)


def _logit(p: np.ndarray) -> np.ndarray:
    p = np.clip(p, 1e-4, 1 - 1e-4)
    return np.log(p / (1 - p))


def expected_calibration_error(y: np.ndarray, p: np.ndarray, bins: int = 10) -> float:
    edges = np.linspace(0, 1, bins + 1)
    idx = np.clip(np.digitize(p, edges[1:-1]), 0, bins - 1)
    ece = 0.0
    for b in range(bins):
        m = idx == b
        if m.any():
            ece += m.mean() * abs(y[m].mean() - p[m].mean())
    return float(ece)


def reliability_bins(y: np.ndarray, p: np.ndarray, bins: int = 10) -> list[dict]:
    edges = np.linspace(0, 1, bins + 1)
    idx = np.clip(np.digitize(p, edges[1:-1]), 0, bins - 1)
    out = []
    for b in range(bins):
        m = idx == b
        if m.any():
            out.append({"bin": b, "mean_predicted": round(float(p[m].mean()), 4),
                        "observed_rate": round(float(y[m].mean()), 4), "count": int(m.sum())})
    return out


def score(y: np.ndarray, p: np.ndarray) -> dict:
    p = np.clip(p, 1e-4, 1 - 1e-4)
    return {"auc": round(float(roc_auc_score(y, p)), 4), "pr_auc": round(float(average_precision_score(y, p)), 4),
            "brier": round(float(brier_score_loss(y, p)), 4), "log_loss": round(float(log_loss(y, p)), 4),
            "ece": round(expected_calibration_error(y, p), 4)}


@dataclass
class RiskPrediction:
    probability: float
    model_version: str


class RiskModel:
    def __init__(self, gbm, calibrator: dict, background: np.ndarray, meta: dict):
        self.gbm = gbm
        self.calibrator = calibrator
        self.background = background
        self.meta = meta

    # ---- properties -------------------------------------------------------
    @property
    def version(self) -> str:
        return self.meta["version"]

    @property
    def card(self) -> dict:
        return self.meta

    # ---- inference --------------------------------------------------------
    def _calibrate(self, raw: np.ndarray) -> np.ndarray:
        kind, model = self.calibrator["kind"], self.calibrator["model"]
        if kind == "platt":
            p = model.predict_proba(_logit(raw).reshape(-1, 1))[:, 1]
        elif kind == "isotonic":
            p = model.predict(raw)
        else:
            p = raw
        return np.clip(p, 0.005, 0.995)

    def predict_matrix(self, X: np.ndarray) -> np.ndarray:
        return self._calibrate(self.gbm.predict_proba(X)[:, 1])

    def predict(self, fi: F.FeatureInput) -> float:
        return float(self.predict_matrix(F.build_row(fi).reshape(1, -1))[0])

    def explain(self, fi: F.FeatureInput, top_k: int = 4) -> list[dict]:
        """Interventional group attribution: how much does each feature group
        move this prediction relative to a typical (background) case? For each
        group we resample its columns from the background set and average the
        prediction; contribution = p(actual) - mean p(resampled). Positive
        means the factor *raises* recovery odds. Cheap (one batched predict)
        and model-agnostic; contributions are approximate and need not sum to
        the total deviation from the base rate."""
        x = F.build_row(fi)
        bg = self.background
        batch = [x.reshape(1, -1)]
        spans = []
        for g, idx in F.GROUP_INDICES.items():
            m = np.tile(x, (len(bg), 1))
            m[:, idx] = bg[:, idx]
            batch.append(m)
            spans.append(g)
        probs = self.predict_matrix(np.vstack(batch))
        p0 = float(probs[0])
        out = []
        for i, g in enumerate(spans):
            seg = probs[1 + i * len(bg): 1 + (i + 1) * len(bg)]
            out.append({"factor": g, "detail": describe_group(g, fi), "effect": round(p0 - float(seg.mean()), 4)})
        out.sort(key=lambda d: abs(d["effect"]), reverse=True)
        return out[:top_k]

    # ---- persistence ------------------------------------------------------
    def save(self, path) -> None:
        joblib.dump({"gbm": self.gbm, "calibrator": self.calibrator, "background": self.background,
                     "meta": self.meta}, path)

    @classmethod
    def load(cls, path) -> "RiskModel":
        blob = joblib.load(path)
        from app.ml import registry
        registry.check_sklearn_version(blob["meta"])
        m = cls(blob["gbm"], blob["calibrator"], blob["background"], blob["meta"])
        if blob["meta"].get("feature_columns") != F.FEATURE_COLUMNS:
            raise RuntimeError("Feature schema changed since this model was trained; retrain required.")
        if blob["meta"].get("feature_fingerprint") != F.fingerprint():
            raise RuntimeError("Feature semantics changed since this model was trained; retrain required.")
        return m


def describe_group(group: str, fi: F.FeatureInput) -> str:
    if group == "Failure reason":
        return (fi.reason or "unknown").replace("_", " ")
    if group == "Payment method":
        return fi.method or "unknown"
    if group == "Amount":
        return f"₹{fi.amount:,.0f}"
    if group == "Attempt history":
        return f"{fi.retry_count} retries, {fi.comms_sent} messages so far"
    if group == "Time since failure":
        return f"{fi.age_hours:.1f}h since failure"
    if group == "Time of day":
        return f"{int(fi.local_hour_frac):02d}:00 local"
    if group == "Salary window / weekend":
        sal = "salary window" if (1 <= fi.day_of_month <= 7 or fi.day_of_month >= 28) else "mid-month"
        return f"{sal}{', weekend' if fi.weekday >= 5 else ''}"
    if group == "Customer history":
        return f"{fi.cust_n} past payments, {F.smooth_rate(fi.cust_captured, fi.cust_n) * 100:.0f}% success"
    return ""


