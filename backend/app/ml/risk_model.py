def build_synthetic_dataset(n_cases: int, seed: int):
    cases = generate_cases(n_cases, seed, BASE_WORLD)
    pol = RulesPolicy()
    X, y, cid, cat_rule_p, category = [], [], [], [], []
    for c in cases:
        res = run_episode(c, pol, pol.plan(c), BASE_WORLD, log_states=True)
        cat = rules.classify_failure(c.reason)
        for fi, k, comms in res.states:
            X.append(F.build_row(fi))
            y.append(1 if res.recovered else 0)
            cid.append(c.cid)
            cat_rule_p.append(rules.risk_assessment(cat, k))
            category.append(cat)
    return (np.vstack(X), np.array(y), np.array(cid), np.array(cat_rule_p), np.array(category))


def _grouped_permutation_importance(gbm_predict, X, y, rng, repeats: int = 3) -> list[dict]:
    base = log_loss(y, np.clip(gbm_predict(X), 1e-4, 1 - 1e-4))
    out = []
    for g, idx in F.GROUP_INDICES.items():
        deltas = []
        for _ in range(repeats):
            Xp = X.copy()
            perm = rng.permutation(len(X))
            Xp[:, idx] = X[perm][:, idx]
            deltas.append(log_loss(y, np.clip(gbm_predict(Xp), 1e-4, 1 - 1e-4)) - base)
        out.append({"factor": g, "importance": round(float(np.mean(deltas)), 4)})
    out.sort(key=lambda d: d["importance"], reverse=True)
    return out


def train_risk_model(n_cases: int = 20000, seed: int = 42, real_rows: tuple | None = None,
                     quiet: bool = True) -> RiskModel:
    """Train + evaluate + calibrate. `real_rows=(X, y)` optionally adds logged
    production outcomes (from the ml_decisions table) to the training split and
    reports an additional held-out real-data score."""
    rng = np.random.default_rng(seed)
    X, y, cid, rule_p, category = build_synthetic_dataset(n_cases, seed)

    # Time-ordered split at the CASE level (cases are already sorted by arrival time).
    n = int(cid.max()) + 1
    cut = lambda f: int(n * f)
    tr, va, ca = cid < cut(0.65), (cid >= cut(0.65)) & (cid < cut(0.75)), (cid >= cut(0.75)) & (cid < cut(0.85))
    te = cid >= cut(0.85)

    real_info = {"rows": 0}
    X_train, y_train = X[tr], y[tr]
    X_real_test = y_real_test = None
    if real_rows is not None and len(real_rows[1]) >= 50:
        Xr, yr = real_rows
        order = rng.permutation(len(yr))
        split = int(0.8 * len(yr))
        X_train = np.vstack([X_train, Xr[order[:split]]])
        y_train = np.concatenate([y_train, yr[order[:split]]])
        X_real_test, y_real_test = Xr[order[split:]], yr[order[split:]]
        real_info = {"rows": int(len(yr)), "used_for_training": int(split), "held_out": int(len(yr) - split)}

    gbm = HistGradientBoostingClassifier(
        learning_rate=0.06, max_iter=400, max_depth=6, min_samples_leaf=40, l2_regularization=1.0,
        monotonic_cst=F.monotonic_vector(), early_stopping=False, random_state=seed)
    gbm.fit(X_train, y_train)

    # Pick the number of boosting rounds on the validation split.
    best_iter, best_ll = gbm.n_iter_, 9.9
    for i, p in enumerate(gbm.staged_predict_proba(X[va]), start=1):
        ll = log_loss(y[va], np.clip(p[:, 1], 1e-4, 1 - 1e-4))
        if ll < best_ll:
            best_ll, best_iter = ll, i
    if best_iter < gbm.n_iter_:
        gbm = HistGradientBoostingClassifier(
            learning_rate=0.06, max_iter=best_iter, max_depth=6, min_samples_leaf=40, l2_regularization=1.0,
            monotonic_cst=F.monotonic_vector(), early_stopping=False, random_state=seed).fit(X_train, y_train)

    # Calibration: fit Platt and isotonic on the calibration split, keep the better on validation.
    raw = lambda M: gbm.predict_proba(M)[:, 1]
    platt = LogisticRegression(C=1e6, max_iter=1000).fit(_logit(raw(X[ca])).reshape(-1, 1), y[ca])
    iso = IsotonicRegression(y_min=0.005, y_max=0.995, out_of_bounds="clip").fit(raw(X[ca]), y[ca])
    cand = {"platt": lambda r: platt.predict_proba(_logit(r).reshape(-1, 1))[:, 1], "isotonic": lambda r: iso.predict(r)}
    scored = {k: log_loss(y[va], np.clip(f(raw(X[va])), 1e-4, 1 - 1e-4)) for k, f in cand.items()}
    kind = min(scored, key=scored.get)
    calibrator = {"kind": kind, "model": platt if kind == "platt" else iso}

    bg_idx = rng.choice(np.where(tr)[0], size=min(64, int(tr.sum())), replace=False)
    meta = {
        "feature_columns": F.FEATURE_COLUMNS, "feature_fingerprint": F.fingerprint(), "trained_at": datetime.now(timezone.utc).replace(tzinfo=None).isoformat(timespec="seconds") + "Z",
        "algorithm": "HistGradientBoostingClassifier (monotonic constraints) + " + kind + " calibration",
        "best_iterations": int(best_iter), "calibration": kind, "seed": seed,
        "sklearn_version": sklearn.__version__, "python_version": platform.python_version(),
        "data_provenance": DATA_PROVENANCE, "real_data": real_info,
        "dataset": {"n_cases": n_cases, "n_rows": int(len(y)), "positive_rate": round(float(y.mean()), 4),
                    "split": "time-ordered by case: 65% train / 10% val / 10% calibration / 15% test",
                    "test_rows": int(te.sum())},
    }
    model = RiskModel(gbm, calibrator, X[tr][bg_idx], meta)

    # ---- evaluation on the untouched test split ---------------------------
    Xt, yt = X[te], y[te]
    p_gbm = model.predict_matrix(Xt)
    lr = make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000)).fit(X_train, y_train)
    p_lr = lr.predict_proba(Xt)[:, 1]
    p_raw = np.clip(raw(Xt), 1e-4, 1 - 1e-4)
    p_rule = rule_p[te]
    prevalence = np.full_like(p_gbm, float(y[tr].mean()))

    metrics = {
        "gbm_calibrated": score(yt, p_gbm), "gbm_uncalibrated": score(yt, p_raw),
        "logistic_regression": score(yt, p_lr), "rules_baseline": score(yt, p_rule),
        "prevalence_only": {k: v for k, v in score(yt, prevalence).items() if k not in ("auc", "pr_auc")},
    }
    by_cat = []
    for cat in ("soft_decline", "technical", "hard_decline", "unknown"):
        m = category[te] == cat
        if m.sum() > 50 and len(set(yt[m])) == 2:
            by_cat.append({"category": cat, "rows": int(m.sum()), "observed_rate": round(float(yt[m].mean()), 3),
                           "mean_predicted": round(float(p_gbm[m].mean()), 3),
                           "rules_baseline_predicted": round(float(p_rule[m].mean()), 3),
                           "auc": round(float(roc_auc_score(yt[m], p_gbm[m])), 3)})
    importance = _grouped_permutation_importance(model.predict_matrix, Xt[: min(len(Xt), 6000)],
                                                 yt[: min(len(Xt), 6000)], rng)
    model.meta["metrics"] = metrics
    model.meta["metrics_by_category"] = by_cat
    model.meta["reliability"] = {"model": reliability_bins(yt, p_gbm), "rules_baseline": reliability_bins(yt, p_rule)}
    model.meta["feature_importance"] = importance
    if X_real_test is not None and len(set(y_real_test)) == 2:
        model.meta["real_holdout_metrics"] = score(y_real_test, model.predict_matrix(X_real_test))

    model.meta["version"] = "risk-gbm-" + datetime.now(timezone.utc).strftime("%Y%m%d") + "-" + hashlib.sha1(
        json.dumps([n_cases, seed, real_info, F.FEATURE_COLUMNS, sklearn.__version__]).encode()).hexdigest()[:8]
    return model
